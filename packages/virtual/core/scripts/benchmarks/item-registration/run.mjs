import { resolve } from "node:path";
import { chromium, firefox, webkit } from "@playwright/test";
import { build } from "esbuild";
import {
    formatMarkdownTable,
    getEnvironmentDescription,
    writeBenchmarkReport
} from "../utils.mjs";

const packageRoot = resolve(import.meta.dirname, "../../..");
const outputPath = resolve(
    process.env.ITEM_REGISTRATION_BENCH_OUTPUT ??
        resolve(import.meta.dirname, "latest.md")
);
const bundle = await build({
    bundle: true,
    define: {
        "process.env.NODE_ENV": '"production"'
    },
    entryPoints: [
        resolve(packageRoot, "src/benchmarks/itemRegistrationFixture.ts")
    ],
    format: "iife",
    globalName: "ItemRegistrationFixture",
    nodePaths: [resolve(packageRoot, "../react/node_modules")],
    platform: "browser",
    target: "esnext",
    write: false
});
const fixtureCode = bundle.outputFiles[0].text;
const selectedEngines = new Set(
    (
        process.env.ITEM_REGISTRATION_BENCH_ENGINES ?? "chromium,firefox,webkit"
    ).split(",")
);
const rows = [];

// oxlint-disable eslint/no-await-in-loop -- Engines must run sequentially to avoid cross-browser CPU contention.
for (const [engineName, displayName, engine, executablePath] of [
    [
        "chromium",
        "Chromium",
        chromium,
        process.env.ITEM_REGISTRATION_BENCH_CHROMIUM_EXECUTABLE_PATH
    ],
    [
        "firefox",
        "Firefox",
        firefox,
        process.env.ITEM_REGISTRATION_BENCH_FIREFOX_EXECUTABLE_PATH
    ],
    [
        "webkit",
        "WebKit",
        webkit,
        process.env.ITEM_REGISTRATION_BENCH_WEBKIT_EXECUTABLE_PATH
    ]
]) {
    if (!selectedEngines.has(engineName)) continue;

    const browser = await engine.launch({ executablePath, headless: true });
    try {
        const page = await browser.newPage();
        await page.addScriptTag({ content: fixtureCode });
        const results = await page.evaluate(() =>
            globalThis.ItemRegistrationFixture.runItemRegistrationBenchmark()
        );

        for (const result of results) {
            const row = [
                displayName,
                browser.version(),
                result.scenario,
                result.refs.toFixed(2),
                result.vertical.toFixed(2),
                result.horizontal.toFixed(2),
                `${((result.vertical / result.refs - 1) * 100).toFixed(1)}%`,
                `${((result.horizontal / result.refs - 1) * 100).toFixed(1)}%`
            ];
            rows.push(row);
            const consoleRow = {
                engine: engineName,
                scenario: result.scenario,
                "refs + WeakMap µs/update": result.refs.toFixed(2),
                "MO + row attr µs/update": result.vertical.toFixed(2),
                "MO + col attr µs/update": result.horizontal.toFixed(2),
                "row delta": `${((result.vertical / result.refs - 1) * 100).toFixed(1)}%`,
                "col delta": `${((result.horizontal / result.refs - 1) * 100).toFixed(1)}%`
            };
            console.table([consoleRow]);
        }
    } finally {
        await browser.close();
    }
}
// oxlint-enable eslint/no-await-in-loop

if (rows.length === 0) {
    throw new Error("No benchmark engines were selected");
}

await writeBenchmarkReport(outputPath, [
    "# Item registration browser benchmark",
    "",
    "<!-- Generated by pnpm nx run @af-utils/virtual-core:bench:items:browser. Do not edit manually. -->",
    "",
    `Generated: ${new Date().toISOString()}`,
    "",
    `Environment: ${getEnvironmentDescription()}`,
    "",
    "Lower timings are better. Deltas compare MutationObserver registration with explicit refs and a WeakMap.",
    "",
    ...formatMarkdownTable(
        [
            "Engine",
            "Version",
            "Scenario",
            "Refs + WeakMap, µs/update",
            "MO + row attr, µs/update",
            "MO + col attr, µs/update",
            "Row delta",
            "Col delta"
        ],
        rows,
        new Set([3, 4, 5, 6, 7])
    ),
    ""
]);
