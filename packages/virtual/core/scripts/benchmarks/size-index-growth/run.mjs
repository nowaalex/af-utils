import { resolve } from "node:path";
import { chromium, firefox, webkit } from "@playwright/test";
import {
    formatMarkdownTable,
    getEnvironmentDescription,
    writeBenchmarkReport
} from "../utils.mjs";
import { runSizeIndexGrowthBenchmark } from "./fixture.mjs";

const outputPath = resolve(
    process.env.SIZE_INDEX_GROWTH_BENCH_OUTPUT ??
        resolve(import.meta.dirname, "latest.md")
);
const selectedEngines = new Set(
    (
        process.env.SIZE_INDEX_GROWTH_BENCH_ENGINES ??
        "node,chromium,firefox,webkit"
    ).split(",")
);
const engineResults = [];

if (selectedEngines.has("node")) {
    engineResults.push({
        engine: "Node",
        version: `${process.version} / V8 ${process.versions.v8}`,
        benchmark: runSizeIndexGrowthBenchmark()
    });
}

// oxlint-disable eslint/no-await-in-loop -- Engines run sequentially to avoid cross-browser CPU contention.
for (const [engineName, displayName, engine, executablePath] of [
    [
        "chromium",
        "Chromium",
        chromium,
        process.env.SIZE_INDEX_GROWTH_BENCH_CHROMIUM_EXECUTABLE_PATH
    ],
    [
        "firefox",
        "Firefox",
        firefox,
        process.env.SIZE_INDEX_GROWTH_BENCH_FIREFOX_EXECUTABLE_PATH
    ],
    [
        "webkit",
        "WebKit",
        webkit,
        process.env.SIZE_INDEX_GROWTH_BENCH_WEBKIT_EXECUTABLE_PATH
    ]
]) {
    if (!selectedEngines.has(engineName)) continue;

    const browser = await engine.launch({ executablePath, headless: true });
    try {
        const page = await browser.newPage();
        const benchmark = await page.evaluate(runSizeIndexGrowthBenchmark);
        engineResults.push({
            engine: displayName,
            version: browser.version(),
            benchmark
        });
    } finally {
        await browser.close();
    }
}
// oxlint-enable eslint/no-await-in-loop

if (engineResults.length === 0) {
    throw new Error("No benchmark engines were selected");
}

const supportedResult = engineResults.find(
    result => result.benchmark.supported
);
if (!supportedResult) {
    throw new Error("No selected engine supports all three growth strategies");
}

const formatMilliseconds = value => value.toFixed(3);
const formatDelta = (value, baseline) => {
    const delta = (value / baseline - 1) * 100;
    return `${delta > 0 ? "+" : ""}${delta.toFixed(1)}%`;
};
const lines = [
    "# SizeIndex typed-array growth benchmark",
    "",
    "<!-- Generated by pnpm nx run @af-utils/virtual-core:bench:size-index-growth. Do not edit manually. -->",
    "",
    `Generated: ${new Date().toISOString()}`,
    "",
    `Environment: ${getEnvironmentDescription()}`,
    "",
    `Each sample grows from zero to ${supportedResult.benchmark.targetCapacity.toLocaleString("en-US")} ` +
        `Float64 slots in ${supportedResult.benchmark.growthSteps} geometric steps. ` +
        `The table contains medians of ${supportedResult.benchmark.measuredRounds} measured rounds after warmup.`,
    "Each timed round repeats the complete growth sequence 16 times, then reports milliseconds per sequence to reduce browser timer quantization.",
    "Lower timings are better. Deltas are relative to allocate + fill + set; negative is faster.",
    ""
];
const tableRows = [];

for (const { engine, version, benchmark } of engineResults) {
    if (!benchmark.supported) {
        tableRows.push([
            engine,
            version,
            "n/a",
            "n/a",
            "n/a",
            "n/a",
            benchmark.reason
        ]);
        continue;
    }

    const { result } = benchmark;
    tableRows.push([
        engine,
        version,
        formatMilliseconds(result.allocateMilliseconds),
        formatMilliseconds(result.transferMilliseconds),
        formatDelta(result.transferMilliseconds, result.allocateMilliseconds),
        formatMilliseconds(result.resizeMilliseconds),
        formatDelta(result.resizeMilliseconds, result.allocateMilliseconds)
    ]);
}

lines.push(
    ...formatMarkdownTable(
        [
            "Engine",
            "Version",
            "Allocate + set, ms",
            "`transferToFixedLength`, ms",
            "Δ vs allocate",
            "`resize`, ms",
            "Δ vs allocate"
        ],
        tableRows,
        new Set([2, 3, 4, 5, 6])
    ),
    ""
);

lines.push(
    "## Strategies",
    "",
    "- **Allocate + set:** allocate a fixed `Float64Array`, fill it with the estimate, then copy the old view with `set`.",
    "- **transferToFixedLength:** transfer each fixed backing buffer to the new byte length, recreate its view, and fill only the newly exposed size slots.",
    "- **resize:** create length-tracking views over resizable buffers, reserve the target as `maxByteLength`, resize for every growth step, and fill only newly exposed size slots.",
    "",
    "This benchmark intentionally measures only growing the `_sizes` typed array while preserving its contents and initializing the new tail. It does not allocate or rebuild the Fenwick tree. Results are machine- and engine-specific; rerun on the target hardware before changing production code.",
    "",
    "`SizeIndex` currently uses `transferToFixedLength`, preserving fixed-length buffers for its hot runtime accesses.",
    ""
);

await writeBenchmarkReport(outputPath, lines);
